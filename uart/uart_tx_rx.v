`timescale 1ns / 1ns

// ----------------------------------------------------------------
// Module   : uart_top
// Author   : 平の路
// Function : UART 串口回环顶层模块 (接收什么就发送什么)
// ----------------------------------------------------------------
module uart_top #(
    parameter integer CLK_FREQ  = 50_000_000, // 系统时钟频率 50MHz
    parameter integer BAUD_RATE = 9600        // 波特率 9600
)(
    input  wire i_clk,      // 系统时钟 (板载 50MHz 晶振)
    input  wire i_rst_n,    // 低电平异步复位 (板载按键)
    input  wire i_rx,       // FPGA 的物理串口接收引脚 (接 USB转串口模块的 TXD)
    output wire o_tx        // FPGA 的物理串口发送引脚 (接 USB转串口模块的 RXD)
);

    // =================================================================
    // 内部连接线声明 (纯粹的 wire 导线，对应硅片上的金属连线)
    // =================================================================
    wire [7:0] w_rx_data;   // 接收模块吐出的并行数据
    wire       w_rx_done;   // 接收模块吐出的完成脉冲
    wire       w_tx_ready;  // 发送模块的忙闲状态 (1=空闲)

    // =================================================================
    // 实例化子模块 1：接收器 (UART RX)
    // =================================================================
    uart_rx #(
        .CLK_FREQ  (CLK_FREQ),
        .BAUD_RATE (BAUD_RATE),
        .DATA_BITS (8)
    )uart_rx_inst0 (
        .i_clk      (i_clk),
        .i_rst_n    (i_rst_n),
        .i_rx       (i_rx),
        .i_rx_valid (1'b1),        // 恒定使能接收
        .o_rx_data  (w_rx_data),   // 连到内部数据总线
        .o_rx_done  (w_rx_done)    // 连到内部完成脉冲
    );

    // =================================================================
    // 实例化子模块 2：发送器 (UART TX)
    // =================================================================
    uart_tx #(
        .CLK_FREQ  (CLK_FREQ),
        .BAUD_RATE (BAUD_RATE),
        .BIT_COUNT (8)
    )uart_tx_inst0 (
        .i_clk      (i_clk),
        .i_rst_n    (i_rst_n),
        // 【核心桥梁思维】：
        // 接收端一完成收数 (w_rx_done)，立刻触发发送端的有效脉冲 (i_tx_valid)！
        .i_tx_valid (w_rx_done),
        // 把接收端吐出的数据，原封不动喂给发送端的数据口袋！
        .i_tx_data  (w_rx_data),
        .o_tx       (o_tx),        // 连到芯片外部物理引脚
        .o_tx_ready (w_tx_ready)   // 监测发送忙闲（回环测试中暂不强制干预）
    );

// ====================================================================
//                          导师的核心硬件提醒
// ====================================================================
/*
  当你在顶层把 u_uart_rx 和 u_uart_tx 写在一起时，千万不要把它当成 C 语言的“函数调用”。
  在底层硅片上，综合器（Synthesizer）并不会去“跳转执行代码”。
  它做的事情是：
  1. 在芯片里划出一片区域，把 u_uart_rx 的逻辑门（LUT/DFF）焊好。
  2. 在旁边划出另一片区域，把 u_uart_tx 的逻辑门焊好。
  3. 用一根肉眼看不见的金属导线（wire），把 rx 的 o_rx_done 直接焊接到 tx 的 i_tx_valid 上！
  这就是真正的**硬件并行架构**！
*/

endmodule